/* equipment-service-tests.js — due math for machine service (js/191). Pure node. */
const S = require("./js/191-equipment-service.js"); let n = 0, f = 0;
const eq = (a, b, m) => { n++; if (JSON.stringify(a) !== JSON.stringify(b)) { f++; console.log("FAIL", m, JSON.stringify(a), "want", JSON.stringify(b)); } };
const DAY = 86400000, T0 = 1700000000000;
const plan = [{ key: "oil", label: "Oil", first: 10, every: 50, days: 182 }, { key: "hyd", label: "Hyd", first: 50, every: 500 }, { key: "levels", label: "Levels", every: 10 }];
const st = (svc, t) => Object.fromEntries(S.svcStatus(svc, t).map(r => [r.key, r]));
let r = st({ hours: 0, start: T0, plan }, T0);
eq(r.oil.dueHours, 10, "first oil change is the break-in figure, not the interval");
eq(r.oil.state, "ok", "at 0 h nothing is due");
eq(r.hyd.dueHours, 50, "first hydraulic change at 50");
eq(r.levels.dueHours, 10, "no break-in figure → the interval");
r = st({ hours: 6, start: T0, plan }, T0);
eq(r.oil.state, "soon", "within 5 h of due → soon");
r = st({ hours: 12, start: T0, plan }, T0);
eq(r.oil.state, "overdue", "past the break-in hours → overdue");
eq(r.oil.remainHours, -2, "shows how far over");
r = st({ hours: 12, start: T0, plan, log: [{ key: "oil", at: T0 + DAY, hours: 11 }] }, T0 + 2 * DAY);
eq(r.oil.dueHours, 61, "after the first change the next is last + interval");
eq(r.oil.state, "ok", "…and it is fine again");
eq(r.oil.last.hours, 11, "last service is carried on the row");
r = st({ hours: 0, start: T0, plan }, T0 + 200 * DAY);
eq(r.oil.state, "overdue", "calendar rule: 182 days passed even though hours are low");
eq(r.oil.remainDays, -18, "days over");
r = st({ hours: 0, start: T0, plan }, T0 + 170 * DAY);
eq(r.oil.state, "soon", "within 14 days → soon");
eq(S.svcStatus({ hours: 12, plan }, T0)[0].key, "oil", "most overdue sorts first");
eq(S.svcStatus(null, T0), [], "no service block → empty");
eq(S.svcLast([{ key: "a", at: 1 }, { key: "a", at: 5 }, { key: "b", at: 9 }], "a").at, 5, "latest entry for a key");
eq(S.SVC_PLAN_SKID.find(p => p.key === "oil").first, 10, "skid plan: first oil change at 10 h per RATO");
eq(S.SVC_PLAN_SKID.find(p => p.key === "hyd_oil").every, 500, "skid plan: hydraulic oil every 500 h");
console.log("=========  " + (n - f) + " passed, " + f + " failed  ========="); process.exit(f ? 1 : 0);
