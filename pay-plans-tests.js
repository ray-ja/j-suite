/* pay-plans-tests.js — in-house pay over time (js/192): schedule math, status, what the sweep sends. Pure node. */
const P = require("./js/192-pay-plans.js"); let n = 0, f = 0;
const eq = (a, b, m) => { n++; if (JSON.stringify(a) !== JSON.stringify(b)) { f++; console.log("FAIL", m, JSON.stringify(a), "want", JSON.stringify(b)); } };
const sum = rows => rows.reduce((s, r) => s + r.cents, 0);
let s = P.ppSchedule(177000, { n: 4, unit: "month", start: "2026-10-01" });
eq(s.length, 4, "four monthly payments");
eq(sum(s), 177000, "cents add up exactly");
eq(s.map(r => r.due), ["2026-10-01", "2026-11-01", "2026-12-01", "2027-01-01"], "monthly dates roll the year");
eq(s.map(r => r.cents), [44250, 44250, 44250, 44250], "even split when it divides");
s = P.ppSchedule(100000, { n: 3, unit: "week", start: "2026-09-30" });
eq(s.map(r => r.cents), [33333, 33333, 33334], "remainder lands on the last payment");
eq(s.map(r => r.due), ["2026-09-30", "2026-10-07", "2026-10-14"], "weekly dates");
s = P.ppSchedule(100000, { n: 4, unit: "2week", start: "2026-10-02", depositCents: 25000 });
eq(s[0], Object.assign({}, s[0], { n: 1, due: "2026-10-02", cents: 25000, deposit: true }), "deposit is payment 1 on the start date");
eq(s.slice(1).map(r => r.cents), [25000, 25000, 25000], "rest split evenly after the deposit");
eq(s.slice(1).map(r => r.due), ["2026-10-16", "2026-10-30", "2026-11-13"], "every two weeks after the deposit");
eq(P.ppSchedule(50000, { n: 2, unit: "days", every: 10, start: "2026-10-01" }).map(r => r.due), ["2026-10-01", "2026-10-11"], "custom N days");
eq(P.ppAddMonths("2026-01-31", 1), "2026-02-28", "month-end clamps");
eq(P.ppSchedule(0, { n: 3 }).length, 3, "zero total still builds rows");
eq(sum(P.ppSchedule(99999, { n: 7, unit: "month", start: "2026-10-01" })), 99999, "odd cents add up");
const plan = { status: "active", autoSend: true, installments: P.ppSchedule(90000, { n: 3, unit: "month", start: "2026-10-01" }) };
let st = P.ppStatus(plan, "2026-09-26");
eq(st.rows.map(r => r.state), ["upcoming", "upcoming", "upcoming"], "before the first due date");
eq(st.next.n, 1, "next is payment 1");
eq(st.remainingCents, 90000, "nothing paid");
plan.installments[0].paidCents = 30000; plan.installments[0].sentAt = 1;
st = P.ppStatus(plan, "2026-11-05");
eq(st.rows.map(r => r.state), ["paid", "overdue", "upcoming"], "payment 2 is late on Nov 5");
eq(st.rows[1].daysLate, 4, "four days late");
eq(st.paidCents, 30000, "paid so far");
eq(st.done, false, "not done");
plan.installments[1].paidCents = 30000; plan.installments[2].paidCents = 30000;
eq(P.ppStatus(plan, "2026-12-01").done, true, "all paid → done");
const cfg = { daysBefore: 3, remindAfterDays: [3, 7, 14] };
const p2 = { status: "active", autoSend: true, installments: P.ppSchedule(60000, { n: 2, unit: "month", start: "2026-10-01" }) };
eq(P.ppDueToSend(p2, "2026-09-27", cfg), { send: [], remind: [] }, "4 days out: nothing yet");
eq(P.ppDueToSend(p2, "2026-09-28", cfg).send, [1], "3 days out: send payment 1");
p2.installments[0].sentAt = 1;
eq(P.ppDueToSend(p2, "2026-10-03", cfg), { send: [], remind: [] }, "2 days late: no reminder yet");
eq(P.ppDueToSend(p2, "2026-10-04", cfg).remind, [{ n: 1, day: 3 }], "3 days late: first reminder");
p2.installments[0].reminded = [3];
eq(P.ppDueToSend(p2, "2026-10-06", cfg).remind, [], "reminder 3 already sent, 7 not reached");
eq(P.ppDueToSend(p2, "2026-10-08", cfg).remind, [{ n: 1, day: 7 }], "7 days late: second reminder");
eq(P.ppDueToSend(p2, "2026-10-30", cfg).send, [2], "payment 2 comes up for sending");
eq(P.ppDueToSend(Object.assign({}, p2, { autoSend: false }), "2026-10-30", cfg), { send: [], remind: [] }, "auto-send off → nothing");
eq(P.ppDueToSend(Object.assign({}, p2, { status: "cancelled" }), "2026-10-30", cfg), { send: [], remind: [] }, "cancelled → nothing");
p2.installments[0].paidCents = 30000;
eq(P.ppDueToSend(p2, "2026-10-30", cfg).remind, [], "paid installment is never reminded");
eq(P.ppCfgParse('{"maxN":6}').maxN, 6, "config overrides defaults");
eq(P.ppCfgParse("garbage").daysBefore, 3, "bad config → defaults");
eq(P.ppMoney(44250), "$442.50", "money format");
eq(P.ppUnitLabel({ unit: "2week" }), "every 2 weeks", "unit label");
console.log("=========  " + (n - f) + " passed, " + f + " failed  ========="); process.exit(f ? 1 : 0);
